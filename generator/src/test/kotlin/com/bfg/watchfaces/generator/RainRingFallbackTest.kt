package com.bfg.watchfaces.generator

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.EnumSource

/**
 * The rain ring draws nothing when the watch has no weather, from v16.
 *
 * v14 gave a drawn weather SLOT an em dash and left the rim ring emitting its
 * `Transform` unconditionally, so a watch with no location permission, no
 * weather set up, or a failed first fetch still drew an arc from whatever that
 * expression yields with no data. Operator ruling, 2026-10-12: draw nothing.
 *
 * `WffSchemaTest.every ring source emits schema-valid WFF` is what proves the
 * arrangement is legal against Google's XSD, which is the whole of the device's
 * own check. These tests cover what the schema cannot see: which faces are
 * wrapped, which are untouched, and that the branch is the ring and not a
 * redesign of it.
 */
class RainRingFallbackTest {

    private fun ring(version: Int, source: RingSource) =
        WffEmitter.emit(DialParams(generatorVersion = version, ring = source))

    /** The ring's own `Condition`, or null when it is not wrapped. */
    private fun ringCondition(xml: String): String? {
        if (!xml.contains("<Condition>")) return null
        return xml.split("<Condition>")
            .drop(1)
            .map { it.substringBefore("</Condition>") }
            .firstOrNull { it.contains("CHANCE_OF_PRECIPITATION") }
    }

    /**
     * Every face saved before v16 emits exactly what it always did.
     *
     * The gate, and the reason for the version branch: a stored face must
     * render the way its author saw it. Asserted for every ring source, not
     * only rain, because the branch is keyed on the source and a gate that
     * caught the wrong one would be invisible here otherwise.
     */
    @ParameterizedTest
    @EnumSource(RingSource::class)
    fun `v15 output is untouched`(source: RingSource) {
        val xml = ring(15, source)
        assertTrue(!xml.contains("WEATHER.IS_AVAILABLE")) {
            "$source at v15 gained an availability test; existing faces must not change"
        }
        assertTrue(!xml.contains("<Condition>") || source == RingSource.NONE) {
            "$source at v15 gained a Condition"
        }
    }

    /** Only the RAIN ring is gated. Steps and battery are always a reading. */
    @ParameterizedTest
    @EnumSource(RingSource::class)
    fun `only the rain ring is gated`(source: RingSource) {
        val wrapped = ring(16, source).contains("WEATHER.IS_AVAILABLE")
        assertEquals(source == RingSource.RAIN, wrapped) {
            "$source: wrapped=$wrapped. Steps and battery can always be read, so " +
            "withholding them would hide a reading that exists."
        }
    }

    /**
     * Steps and battery emit a BYTE-IDENTICAL face at v15 and v16.
     *
     * The bump must buy nothing for a ring that was never the problem. A spot
     * check would pass while the surrounding element moved; this would not.
     *
     * Compared from `<WatchFace` onwards, because the header COMMENT stamps the
     * version it was generated by and so can never match across a bump. That is
     * the only difference the comparison forgives, and everything that renders
     * is inside the comparison.
     */
    @ParameterizedTest
    @EnumSource(value = RingSource::class, names = ["NONE", "STEPS", "BATTERY"])
    fun `the bump changes nothing for a ring that is not rain`(source: RingSource) {
        assertEquals(
            ring(15, source).substringAfter("<WatchFace"),
            ring(16, source).substringAfter("<WatchFace")
        ) { "$source emits a different face at v16 than at v15" }
    }

    /**
     * There is no `Default`, and that is the ruling rather than an oversight.
     *
     * `Default` is `minOccurs="0"`, and the schema's own documentation says it
     * is what shows when no `Compare` succeeds — so omitting it draws nothing.
     * The faint track alone was declined: with no arc over it, the track is
     * pixel for pixel what 0% looks like, which states a figure rather than
     * withholding one.
     */
    @Test
    fun `no weather draws nothing at all, not an empty track`() {
        val condition = ringCondition(ring(16, RingSource.RAIN))
        assertTrue(condition != null) { "the rain ring is not wrapped at v16" }
        assertTrue(!condition!!.contains("<Default>")) {
            "the ring's Condition has a Default branch, so something is still drawn " +
            "when there is no weather"
        }
        // And the whole ring is inside the Compare, not merely its arc: a track
        // left outside would be drawn unconditionally and read as 0%.
        val compare = condition.substringAfter("<Compare").substringBefore("</Compare>")
        assertEquals(2, Regex("<Arc ").findAll(compare).count()) {
            "the track and the arc must BOTH be inside the Compare"
        }
        assertEquals(1, Regex("<PartDraw ").findAll(compare).count())
    }

    /**
     * The available branch asks for exactly what v15 asked for.
     *
     * A fallback that also restyled the normal case would be a redesign
     * wearing a fallback's name — the rule `WeatherFallbackTest` holds for the
     * drawn slots. Compared as the full element, so a changed colour, box or
     * thickness fails too.
     */
    @Test
    fun `the available branch is the v15 ring, unchanged`() {
        val before = ring(15, RingSource.RAIN)
        val expected = "<PartDraw" + before.split("<PartDraw")
            .first { it.contains("CHANCE_OF_PRECIPITATION") }
            .substringBefore("</PartDraw>") + "</PartDraw>"

        val compare = ringCondition(ring(16, RingSource.RAIN))!!
            .substringAfter("<Compare expression=\"hasWeather\">")
            .substringBefore("</Compare>")
            .trim()
        assertEquals(expected.trim(), compare) {
            "the ring drawn when weather IS available is not the one v15 drew"
        }
    }

    /**
     * NOTHING BUT THE RING CHANGED, swept over the parameters that share the rim.
     *
     * The house rule after 2026-09-18: when a branch is keyed on a parameter,
     * sweep that parameter, because one example in the middle of a range proves
     * nothing about an edge with its own code. The ring's neighbours are the
     * ones to sweep here — the clock mode (hands give up the chapter ring to
     * the rim), the seconds (`SecondsBand.crowdedByRing` reads `ring.enabled`),
     * and a dark ink (its own ambient branch, and the track's alpha comes off
     * the ink).
     *
     * Each face is compared with its ring element CUT OUT, so a difference
     * anywhere else in the document fails — which is the claim being made.
     */
    @ParameterizedTest
    @EnumSource(ClockMode::class)
    fun `the bump changed the ring and nothing else`(mode: ClockMode) {
        for (seconds in listOf(false, true)) {
            for (ink in listOf("#231F1B", "#F5F0E6")) {
                // A DRAWN date, which emits an element the default face does
                // not. Left out of the first cut, and a mutation that moved it
                // went unnoticed for exactly that reason.
                for (date in listOf(DateStyle.NONE, DateStyle.WEEKDAY_MONTH_DAY)) {
                    val base = DialParams(
                        ring = RingSource.RAIN, clockMode = mode, showSeconds = seconds,
                        inkColor = ink, dateStyle = date
                    )
                    val before = WffEmitter.emit(base.copy(generatorVersion = 15))
                    val after = WffEmitter.emit(base.copy(generatorVersion = 16))
                    assertEquals(withoutRing(before), withoutRing(after)) {
                        "mode=$mode seconds=$seconds ink=$ink date=$date: the v16 face " +
                        "differs somewhere other than the ring"
                    }
                }
            }
        }
    }

    /**
     * The face with its ring element removed, whichever shape the ring took.
     *
     * v15 emits a bare `PartDraw`; v16 emits a `Condition` around it. Cutting
     * either leaves the rest of the document, which is what the sweep above
     * compares. The header comment goes too: it stamps the version and can
     * never match across a bump.
     */
    private fun withoutRing(xml: String): String {
        val body = xml.substringAfter("<WatchFace")
        val open = if (body.contains("<Condition>")) "<Condition>" else "<PartDraw"
        val close = if (open == "<Condition>") "</Condition>" else "</PartDraw>"
        val head = body.substringBefore("CHANCE_OF_PRECIPITATION")
        val start = head.lastIndexOf(open)
        val end = body.indexOf(close, body.indexOf("CHANCE_OF_PRECIPITATION")) + close.length
        return body.removeRange(start, end)
    }

    /** The sweep is still bound to the source, so the watch keeps it current. */
    @Test
    fun `the sweep is still bound at v16`() {
        assertTrue(
            ring(16, RingSource.RAIN).contains(
                """<Transform target="endAngle" value="clamp([WEATHER.CHANCE_OF_PRECIPITATION], 0, 100) * 3.6"/>"""
            )
        ) { "the rain ring no longer binds its sweep, so it would never move" }
    }

    /**
     * A face with no ring gains nothing: no ring, and no weather test.
     *
     * Not asserted by counting `<Arc>` over the document — the complication
     * glyphs are drawn with arcs too, so that proxy measures the wrong thing.
     * It is the SWEEP that only a ring emits.
     */
    @Test
    fun `no ring still means no ring`() {
        val xml = ring(16, RingSource.NONE)
        assertTrue(!xml.contains("WEATHER.IS_AVAILABLE"))
        assertTrue(!xml.contains("CHANCE_OF_PRECIPITATION"))
        assertTrue(!xml.contains("""target="endAngle"""))
    }

    /**
     * The gate is the VERSION, and it is checked here because nothing else
     * would notice it going missing.
     *
     * `appliesToRing` is the only thing standing between a stored v15 face and
     * a silently rewritten ring.
     */
    @Test
    fun `the gate is keyed on the version and on rain alone`() {
        assertTrue(WeatherFallback.appliesToRing(DialParams(ring = RingSource.RAIN)))
        assertTrue(
            !WeatherFallback.appliesToRing(
                DialParams(generatorVersion = 15, ring = RingSource.RAIN)
            )
        )
        assertTrue(!WeatherFallback.appliesToRing(DialParams(ring = RingSource.STEPS)))
        assertTrue(!WeatherFallback.appliesToRing(DialParams(ring = RingSource.NONE)))
        assertEquals(16, WeatherFallback.RING_SINCE_VERSION)
    }
}
